/**
 * Temporally separated 2024 & 2025 independent replay of the 2026-fixed
 * four-stage search and longest-historical-streak selection.
 * Fixture is pinned from 2d3dthailand/2d3dthailand/2D_history 2026-11-15.
 */
class CherryDiscovery2024And2025HoldoutTest {
    private val dates = DateTimeFormatter.ofPattern("dd-MM-yyyy")
    private fun parse(source: String): Pair<List<HistoricDraw>, Set<LocalDate>> {
        val records = source.trimIndent().lines().map { line ->
            val (d, morning, evening) = line.split(",")
            Triple(LocalDate.parse(d, dates), morning, evening)
        }
        // The upstream feed includes contradictory duplicate 10-06-2025 entries
        // (one "off", one 55/60). Use the complete result rather than accidentally
        // classifying a real trading day as closed.
        val days = records.groupBy { it.first }.mapValues { (_, candidates) ->
            candidates.maxByOrNull { row ->
                (if (validHistoric2D(row.second)) 1 else 0) +
                    (if (validHistoric2D(row.third)) 1 else 0)
            }!!
        }.values.sortedBy { it.first }
        val closed = days.filter { !validHistoric2D(it.second) &&
            !validHistoric2D(it.third) }.map { it.first }.toSet()
        val draws = days.flatMap { (date, morning, evening) ->
            buildList {
                if (validHistoric2D(morning)) add(HistoricDraw(
                    date, DrawSession.MORNING, morning, HistoricSource.HISTORY))
                if (validHistoric2D(evening)) add(HistoricDraw(
                    date, DrawSession.EVENING, evening, HistoricSource.HISTORY))
            }
        }
        return draws to closed
    }

    @Test fun otherYearsReplayOnlyAsOfEarlierHistory() {
        for ((year, data, expectedDraws, expectedClosed) in listOf(
            Year(2024, RAW_2024, 480, 5),
            Year(2025, RAW_2025, 481, 17),
        )) {
            val (draws, closed) = parse(data)
            assertEquals("$" + year + " draws", expectedDraws, draws.size)
            assertEquals("$" + year + " closed", expectedClosed, closed.size)
            val one = CherryDiscoveryWalkForward.replay(draws,
                lastTargets = 80, stages = 1, closedDates = closed)
            val full = CherryDiscoveryWalkForward.replay(draws,
                lastTargets = 80, stages = 4, closedDates = closed)
            assertEquals(240, full.checks.size)
            for (kind in CherryDiscoveryKind.entries) {
                val simple = one.stats(kind)
                val stat = full.stats(kind)
                val records = full.checks.filter { it.kind == kind }
                assertEquals(80, stat.targetCount)
                assertEquals(80, stat.checked + stat.noSelection)
                assertTrue("More stages cannot lower coverage", stat.checked >= simple.checked)
                assertTrue(stat.hits in 0..stat.checked)
                val fits = records.mapNotNull { it.historicalFitStreak }
                println("CHERRY_DISCOVERY_OTHER_YEAR year=" + year +
                    " kind=" + kind + " oneStageChecked=" + simple.checked +
                    " oneStageHits=" + simple.hits + " fourStageChecked=" +
                    stat.checked + " fourStageHits=" + stat.hits +
                    " noSelection=" + stat.noSelection +
                    " maxHistorical=" + (fits.maxOrNull() ?: 0) +
                    " tenPlus=" + fits.count { it >= 10 })
            }
        }
    }

    @Test fun duplicateSourceDayDoesNotEraseCompletedResults() {
        val (draws, closed) = parse(RAW_2025)
        val day = LocalDate.of(2025, 6, 10)
        assertFalse(day in closed)
        assertEquals("55", draws.single { it.date == day &&
            it.session == DrawSession.MORNING }.digit)
        assertEquals("60", draws.single { it.date == day &&
            it.session == DrawSession.EVENING }.digit)
        // An incomplete PM draw is not treated as a completely closed day.
        val partial = LocalDate.of(2025, 3, 28)
        assertFalse(partial in closed)
        assertEquals(1, draws.count { it.date == partial })
    }

