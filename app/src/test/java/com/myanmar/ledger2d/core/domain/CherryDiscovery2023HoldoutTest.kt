/**
 * 2023 is a separate historical validation period, not tuned using 2026.
 * Pinned upstream: 2d3dthailand/2d3dthailand/main/2D_history (2026-11-15).
 */
class CherryDiscovery2023HoldoutTest {
    private val dateFormat = DateTimeFormatter.ofPattern("dd-MM-yyyy")
    private fun fixture(): Pair<List<HistoricDraw>, Set<LocalDate>> {
        val draws = mutableListOf<HistoricDraw>()
        val closed = mutableSetOf<LocalDate>()
        DATA.trimIndent().lines().forEach { s ->
            val (date, am, pm) = s.split(",")
            val d = LocalDate.parse(date, dateFormat)
            if (!validHistoric2D(am) && !validHistoric2D(pm)) {
                closed.add(d)
            } else {
                if (validHistoric2D(am))
                    draws.add(HistoricDraw(d, DrawSession.MORNING, am, HistoricSource.HISTORY))
                if (validHistoric2D(pm))
                    draws.add(HistoricDraw(d, DrawSession.EVENING, pm, HistoricSource.HISTORY))
            }
        }
        return draws to closed
    }

    @Test fun separated2023HistorySupportsSameRulesWithoutRetuning() {
        val (draws, closed) = fixture()
        assertEquals(486, draws.size)
        assertEquals(17, closed.size)
        val report = CherryDiscoveryWalkForward.replay(
            draws, lastTargets = 80, stages = 4, closedDates = closed)
        assertEquals(240, report.checks.size)
        for (kind in CherryDiscoveryKind.entries) {
            val stats = report.stats(kind)
            val fits = report.checks.filter { it.kind == kind }
                .mapNotNull { it.historicalFitStreak }
            assertEquals(80, stats.targetCount)
            assertEquals(80, stats.checked + stats.noSelection)
            assertTrue(stats.hits in 0..stats.checked)
            assertTrue(fits.all { it >= 3 })
            val maxFit = fits.maxOrNull() ?: 0
            val reachedTen = fits.count { it >= 10 }
            println("CHERRY_DISCOVERY_2023 kind=$" + kind +
                " targets=80 checked=" + stats.checked + " hits=" + stats.hits +
                " noSelection=" + stats.noSelection + " bestHistorical=" + maxFit +
                " tenPlusFits=" + reachedTen)
        }
    }

